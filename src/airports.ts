/** ICAO K-prefixed codes and IATA codes both resolve; returns the 3-letter FAA code. */
export function normCode(s: string): string {
  const t = s.trim().toUpperCase();
  if (/^K[A-Z]{3}$/.test(t)) return t.slice(1);
  return t;
}
